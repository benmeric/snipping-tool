def detect_system_language() -> str:
    """Windows UI dilini veya yerel ayarları algılar."""
    try:
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        primary = lang_id & 0x3FF
        if primary in WIN_LANG_MAP:
            mapped = WIN_LANG_MAP[primary]
            if mapped in SUPPORTED_LANGUAGES:
                return mapped
    except Exception:
        pass

    try:
        loc = locale.getlocale()[0]
        if loc:
            code = loc.split("_")[0].lower()
            if code in SUPPORTED_LANGUAGES:
                return code
    except Exception:
        pass

    return "en"


def get_current_language() -> str:
    """Aktif yapılandırmaya göre kullanılan geçerli dili döndürür."""
    saved_pref = config.get("app_language", "system")
    if saved_pref == "system" or saved_pref not in SUPPORTED_LANGUAGES:
        return detect_system_language()
    return saved_pref


def set_language(lang_code: str):
    """Kullanıcının seçtiği dili yapılandırmaya kaydeder ('system' veya dil kodu)."""
    if lang_code == "system" or lang_code in SUPPORTED_LANGUAGES:
        config.set("app_language", lang_code)
        target_lang = detect_system_language() if lang_code == "system" else lang_code
        default_prefixes = {
            "tr": "Ekran_Goruntusu",
            "en": "Screenshot",
            "de": "Screenshot",
            "es": "Captura",
            "fr": "Capture",
            "ru": "Снимок_экрана",
        }
        all_defaults = {
            "Ekran_Goruntusu", "EkranAlintisi", "Alinti", "Gorsel", "Resim",
            "Screenshot", "Snip", "Capture", "ScreenClip", "Image",
            "Bildschirmfoto", "Ausschnitt", "Aufnahme", "Bild",
            "Captura", "Recorte", "CapturaPantalla", "Imagen",
            "CaptureEcran", "Extrait",
            "Снимок_экрана", "Фрагмент", "Скриншот", "Изображение",
        }
        cur_pfx = config.get("snip_filename_prefix", "Ekran_Goruntusu")
        if cur_pfx in all_defaults:
            config.set("snip_filename_prefix", default_prefixes.get(target_lang, "Screenshot"))


def t(key: str, **kwargs) -> str:
    """Belirtilen anahtarın geçerli dildeki çevirisini döndürür."""
    curr_lang = get_current_language()
    val = None
    if curr_lang in TRANSLATIONS and key in TRANSLATIONS[curr_lang]:
        val = TRANSLATIONS[curr_lang][key]
    elif key in TRANSLATIONS["en"]:
        val = TRANSLATIONS["en"][key]
    elif key in TRANSLATIONS["tr"]:
        val = TRANSLATIONS["tr"][key]
    else:
        val = key

    if kwargs and isinstance(val, str):
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


def get_language_dropdown_options() -> list[str]:
    """Ayarlar menüsünde gösterilecek dil seçeneklerini döndürür."""
    # İlk seçenek her zaman Sistem Dili (Varsayılan)
    options = [t("lang_system_default")]
    for code, native_name in SUPPORTED_LANGUAGES.items():
        options.append(f"{native_name} ({code.upper()})")
    return options


def get_language_code_from_option(selected_option: str) -> str:
    """Açılır listeden seçilen metni dil koduna dönüştürür."""
    if not selected_option:
        return "system"
    for lang_dict in TRANSLATIONS.values():
        if selected_option == lang_dict.get("lang_system_default"):
            return "system"
    for code, native_name in SUPPORTED_LANGUAGES.items():
        if f"({code.upper()})" in selected_option or selected_option == native_name:
            return code
    return "system"


def get_current_option_label() -> str:
    """Mevcut ayara göre açılır menüde gösterilecek etiketi döndürür."""
    saved = config.get("app_language", "system")
    if saved == "system":
        return t("lang_system_default")
    if saved in SUPPORTED_LANGUAGES:
        return f"{SUPPORTED_LANGUAGES[saved]} ({saved.upper()})"
    return t("lang_system_default")
